/** 键的显示名：收录过的给中文，否则原样返回键名。 */
export function gameOptionDisplayName(key: string): string {
  return GAME_OPTION_LABELS[key] ?? key;
}

/** 是否收录了中文名（UI 用它决定要不要再显示原始键名）。 */
export function hasGameOptionLabel(key: string): boolean {
  return key in GAME_OPTION_LABELS;
}

